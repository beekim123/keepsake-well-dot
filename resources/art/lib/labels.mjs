export function label(g,text,x,y,color='paper'){
 for(const character of text.toUpperCase()){
  const shape=shapes[character]; if(!shape)throw new Error(`Unsupported review-label character: ${character}`);
  for(let yy=0;yy<5;yy++)for(let xx=0;xx<3;xx++)if(shape[yy*3+xx]==='1')g.px(x+xx,y+yy,color);
  x+=4;
 }
}
